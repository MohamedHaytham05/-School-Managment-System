    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         JPasswordField ACE = new JPasswordField();
        int okCxl = JOptionPane.showConfirmDialog(this, ACE, "Enter New Password", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (okCxl == JOptionPane.OK_OPTION) {
            String newPass = new String(ACE.getPassword());
            JOptionPane.showMessageDialog(this, "Password changed to: " + newPass);
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        JTextField nameField = new JTextField();
        JTextField emailField = new JTextField();
        Object panel = null;
        int result = JOptionPane.showConfirmDialog(this, panel , "Update Info", JOptionPane.OK_CANCEL_OPTION);
        if (result == JOptionPane.OK_OPTION) {
            String name = nameField.getText();
            String email = emailField.getText();
            JOptionPane.showMessageDialog(this, "Updated to:\nName: " + name + "\nEmail: " + email);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

