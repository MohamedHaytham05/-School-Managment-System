    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String name = jTextField1.getText().trim();
    String email = jTextField2.getText().trim();
    String password = new String(jPasswordField1.getPassword()).trim();
    String role = (String) roleComboBox.getSelectedItem();

    if (name.isEmpty() || email.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }

    int id = SchoolManagmentSystem.generateUniqueId(); // Optional helper
    if (role.equals("Student")) {
        Student student = new Student(id, name, email, password, 'A', "2025", "student");
        SchoolManagmentSystem.students.add(student);
    } else {
        Teacher teacher = new Teacher(id, name, email, password, "Teacher");
        SchoolManagmentSystem.teachers.add(teacher);
    }

    JOptionPane.showMessageDialog(this, "Account created. Please login.");
    new Login().setVisible(true);
    this.dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

