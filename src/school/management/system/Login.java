    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        // TODO add your handling code here:
   String email = jTextField1.getText().trim();
        String password = new String(passwordField.getPassword()).trim();

        if (email.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter both email and password.");
            return;
        }

        if (SchoolManagmentSystem.admin.getEmail().equals(email) &&
            SchoolManagmentSystem.admin.getPassword().equals(password)) {
            new Adminpanel().setVisible(true);
            dispose();
            return;
        }

        for (Teacher teacher : SchoolManagmentSystem.teachers) {
            if (teacher.getEmail().equals(email) && teacher.getPassword().equals(password)) {
                new Teacherpanel().setVisible(true);
                dispose();
                return;
            }
        }

        for (Student student : SchoolManagmentSystem.students) {
            if (student.getEmail().equals(email) && student.getPassword().equals(password)) {
                new Studentpanel().setVisible(true);
                dispose();
                return;
            }
        }

        JOptionPane.showMessageDialog(this, "Invalid credentials. Please try again.");
    }//GEN-LAST:event_loginActionPerformed

